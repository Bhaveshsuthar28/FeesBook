export const translateDatabaseText = (text, lang) => {
  if (!text || lang !== "hi") return text;
  
  const normalized = String(text).toLowerCase().trim();
  
  // Direct lookup
  if (dynamicTranslations[normalized]) {
    return dynamicTranslations[normalized];
  }
  
  // Pattern matching for Class/Section names
  if (normalized.startsWith("class ")) {
    const suffix = text.substring(6);
    return `कक्षा ${suffix}`;
  }
  if (normalized.startsWith("section ")) {
    const suffix = text.substring(8);
    return `सेक्शन ${suffix}`;
  }
  if (normalized.startsWith("sec ")) {
    const suffix = text.substring(4);
    return `सेक्शन ${suffix}`;
  }
  
  return text;
};

